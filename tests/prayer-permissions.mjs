// Run with Node 24 and @electric-sql/pglite available on NODE_PATH.
import { createRequire } from "node:module";
const { PGlite } = createRequire(import.meta.url)("@electric-sql/pglite");
import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const db=new PGlite();
const [admin,one,two,outsider,groupA,groupB]=Array.from({length:6},(_,i)=>`00000000-0000-4000-8000-00000000000${i+1}`);
const q=(id)=>`'${id}'`;
await db.exec(`
create role anon; create role authenticated; create role service_role;
create schema auth;
create schema realtime;
create table realtime.messages(id int primary key);
alter table realtime.messages enable row level security;
create function realtime.topic() returns text language sql stable as $$ select 'voice-room:community-general' $$;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('app.user_id',true),'')::uuid $$;
grant usage on schema auth to authenticated;
create table public.profiles(id uuid primary key);
create table public.community_blocks(blocker_id uuid, blocked_id uuid);
create table public.community_group_members(group_id uuid,user_id uuid,muted boolean,muted_until timestamptz,role text default 'member');
create table public.user_push_tokens(user_id uuid, enabled boolean);
create table public.community_admins(user_id uuid);
create function public.is_community_staff(_user_id uuid) returns boolean language sql as $$ select exists(select from public.community_admins where user_id=_user_id) $$;
insert into auth.users values (${q(admin)}),(${q(one)}),(${q(two)}),(${q(outsider)});
insert into public.profiles select id from auth.users;
insert into public.community_admins values (${q(admin)});
insert into public.community_group_members(group_id,user_id,muted,muted_until) values (${q(groupA)},${q(admin)},false,null),(${q(groupB)},${q(admin)},false,null),(${q(groupA)},${q(one)},false,null),(${q(groupB)},${q(one)},false,null),(${q(groupB)},${q(two)},true,null);
insert into public.user_push_tokens values (${q(one)},true),(${q(one)},true),(${q(two)},true),(${q(outsider)},true);
`);
for(const file of ['20261125190000_prayer_audience.sql','20261125191000_community_direct_messages.sql','20261125192000_prayer_room_moderation.sql']) {
 await db.exec(await readFile('supabase/migrations/'+file,'utf8'));
}
async function as(role,id){await db.exec(`reset role; set role ${role}; set app.user_id = '${id}';`);}
const send=(recipient)=>db.query('insert into public.community_direct_messages (recipient_id,body) values ($1,$2)',[recipient,'Hello']);
const read=()=>db.query('select sender_id,recipient_id from public.community_direct_messages');
await as('authenticated',one);
await send(two);
await assert.rejects(db.query('insert into public.community_direct_messages (sender_id,recipient_id,body) values ($1,$2,$3)',[two,one,'forged']));
await as('authenticated',outsider);
assert.equal((await read()).rows.length,0);
await as('authenticated',two);
assert.deepEqual((await read()).rows,[{sender_id:one,recipient_id:two}]);
await db.exec(`reset role; insert into public.community_blocks values (${q(two)},${q(one)});`);
await as('authenticated',one);
await assert.rejects(send(two));
await as('authenticated',two);
await assert.rejects(send(one));
await assert.rejects(db.query('select * from public.community_general_prayer_targets($1,$2)',[admin,[groupA]]));
await as('service_role',admin);
const invite=(caller,groups)=>db.query('select user_id from public.community_general_prayer_targets($1,$2)',[caller,groups]);
assert.equal((await invite(outsider,null)).rows.length,0);
assert.equal((await invite(admin,[groupA,outsider])).rows.length,0);
assert.deepEqual((await invite(admin,[groupA,groupB])).rows,[{user_id:one}]);
assert.equal((await invite(admin,null)).rows.length,0);
await db.exec("reset role; update public.community_general_prayer_cooldown set sent_at=now()-interval '2 minutes';");
await as('service_role',admin);
assert.equal((await invite(admin,null)).rows.length,3);
await as('authenticated',one);
const moderate=(room,target,action)=>db.query('select public.prayer_room_moderate($1,$2,$3)',[room,target,action]);
const room='community-general';
await assert.rejects(moderate(room,two,'turn'));
await as('authenticated',admin);
await moderate(room,one,'moderator');
await as('authenticated',one);
await assert.rejects(moderate(room,two,'moderator'));
await assert.rejects(moderate(room,admin,'remove'));
await assert.rejects(moderate(groupA,two,'turn'));
await moderate(room,two,'turn');
await as('authenticated',two);
assert.ok((await db.query('select public.prayer_room_controls($1) as controls',[room])).rows[0].controls.turn_at);
await as('authenticated',one);
await moderate(room,two,'remove');
await as('authenticated',two);
assert.equal((await db.query('select public.prayer_room_not_removed($1) as allowed',[room])).rows[0].allowed,false);
await assert.rejects(moderate(room,one,'turn'));
await db.close();
console.log('Passed PostgreSQL checks: private reads, spoofed sender, two-way blocks, audience roles, membership, deduplication, mute, cooldown, global audience and room moderation.');
