export function getLocalizedBookName(
  abbrev: string,
  fallback: string,
  language?: string,
): string {
  const entry = BIBLE_BOOK_NAMES[abbrev?.toLowerCase()];
  if (!entry) return fallback;
  const lang = (language === "es" || language === "pt" || language === "en") ? language : "en";
  return entry[lang] || fallback;
}